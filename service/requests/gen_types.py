"""Generate ``contract_types.py`` (TypedDicts) from the bundled contract schemas.

Run: ``python3 -m service.requests.gen_types`` — the unit suite fails if the
committed file differs from a fresh generation, so types can never drift from
docs/creative-studio/contracts/*.schema.json. Validation itself always uses the
schemas (service/requests/contracts.py); these types are for static reading only.
"""
from __future__ import annotations

import json
import keyword
import re
from pathlib import Path

from .contracts import CONTRACTS_DIR

OUT = Path(__file__).with_name("contract_types.py")
SOURCES = ["common.schema.json", "brand-package-v1.schema.json", "creative-request-v1.schema.json",
           "treatment-v1.schema.json", "authoring-draft-v1.schema.json", "operation-v1.schema.json"]


def _camel(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[^A-Za-z0-9]+", name) if part)


class _Gen:
    def __init__(self):
        self.classes: list[str] = []
        self.aliases: list[str] = []
        self.seen: set[str] = set()

    def ref_name(self, ref: str) -> str:
        file, _, pointer = ref.partition("#")
        stem = (file or "common.schema.json").replace(".schema.json", "")
        leaf = pointer.rsplit("/", 1)[-1] if pointer else stem
        return _camel(leaf) if stem == "common" else _camel(stem + "_" + leaf)

    def type_of(self, node: dict, hint: str) -> str:
        if "$ref" in node:
            return self.ref_name(node["$ref"])
        if "const" in node:
            return f"Literal[{node['const']!r}]"
        if "enum" in node:
            return "Literal[" + ", ".join(repr(v) for v in node["enum"]) + "]"
        for key in ("anyOf", "oneOf"):
            if key in node:
                parts = [self.type_of(sub, f"{hint}{i}") for i, sub in enumerate(node[key])]
                uniq = list(dict.fromkeys(parts))
                return uniq[0] if len(uniq) == 1 else "Union[" + ", ".join(uniq) + "]"
        t = node.get("type")
        if isinstance(t, list):
            return "Any"
        if t == "string":
            return "str"
        if t == "integer":
            return "int"
        if t == "number":
            return "float"
        if t == "boolean":
            return "bool"
        if t == "null":
            return "None"
        if t == "array":
            return f"List[{self.type_of(node.get('items', {}), hint + 'Item')}]"
        if t == "object" or "properties" in node:
            if "properties" not in node:
                extra = node.get("additionalProperties")
                if isinstance(extra, dict) and extra:
                    return f"Dict[str, {self.type_of(extra, hint + 'Value')}]"
                return "Dict[str, Any]"
            return self.object_class(hint, node)
        return "Any"

    def object_class(self, name: str, node: dict) -> str:
        if name in self.seen:
            return name
        self.seen.add(name)
        required = set(node.get("required", []))
        fields = []
        for prop, sub in node["properties"].items():
            t = self.type_of(sub, name + _camel(prop))
            fields.append((prop, t if prop in required else f"NotRequired[{t}]"))
        if any(keyword.iskeyword(p) or not p.isidentifier() for p, _ in fields):
            body = ", ".join(f"{p!r}: {t}" for p, t in fields)
            self.classes.append(f"{name} = TypedDict({name!r}, {{{body}}})\n")
        else:
            lines = [f"class {name}(TypedDict):"] + [f"    {p}: {t}" for p, t in fields]
            self.classes.append("\n".join(lines) + "\n")
        return name


def generate() -> str:
    gen = _Gen()
    for source in SOURCES:
        doc = json.loads((CONTRACTS_DIR / source).read_text(encoding="utf-8"))
        stem = source.replace(".schema.json", "")
        for def_name, node in (doc.get("$defs") or {}).items():
            name = _camel(def_name) if stem == "common" else _camel(stem + "_" + def_name)
            t = gen.type_of(node, name)
            if t != name:
                gen.aliases.append(f"{name} = {t}")
        if "properties" in doc:
            gen.object_class(_camel(stem), doc)
    header = ('"""GENERATED by service/requests/gen_types.py from docs/creative-studio/contracts. Do not edit."""\n'
              "# ruff: noqa\nfrom __future__ import annotations\n\n"
              "from typing import Any, Dict, List, Literal, NotRequired, TypedDict, Union\n\n"
              )
    return header + "\n".join(gen.aliases) + "\n\n\n" + "\n\n".join(gen.classes)


if __name__ == "__main__":
    OUT.write_text(generate(), encoding="utf-8")
    print(f"wrote {OUT}")
